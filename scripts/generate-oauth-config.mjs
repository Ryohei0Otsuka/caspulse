import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const envPath = path.join(root, '.env.local');
const outputPath = path.join(root, 'src', 'main', 'generated-oauth-config.ts');

function readDotEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const result = {};
  for (const rawLine of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = line.match(/^([A-Z0-9_]+)\s*=\s*(.*)$/i);
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    result[match[1]] = value;
  }
  return result;
}

const localEnv = readDotEnv(envPath);
const clientId = (process.env.CASPULSE_TWITCASTING_CLIENT_ID ?? localEnv.CASPULSE_TWITCASTING_CLIENT_ID ?? '').trim();

const source = `// AUTO-GENERATED by scripts/generate-oauth-config.mjs\n// Do not commit a private Client Secret here. CASPULSE only embeds the public Client ID.\nexport const CASPULSE_TWITCASTING_CLIENT_ID = ${JSON.stringify(clientId)};\n`;
fs.writeFileSync(outputPath, source, 'utf8');

if (clientId) {
  console.log('[CASPULSE] TwitCasting Client ID embedded for this build.');
} else {
  console.log('[CASPULSE] No Client ID configured. The app will show developer setup guidance.');
}
